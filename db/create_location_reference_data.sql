-- Canonical areas and their aliases are data, not hard-coded application
-- logic. Add/edit aliases here (or through an admin UI) without a deployment.
CREATE TABLE IF NOT EXISTS public.areas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  city text NOT NULL DEFAULT 'Bengaluru',
  latitude double precision,
  longitude double precision
);

CREATE TABLE IF NOT EXISTS public.location_aliases (
  alias_key text PRIMARY KEY,
  area_id bigint NOT NULL REFERENCES public.areas(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now()
);

