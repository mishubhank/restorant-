-- Repair legacy rows from the same alias reference data. The area list keeps
-- its original order and leaves unknown locations untouched.
UPDATE public.listings AS l
SET location = ARRAY(
  SELECT COALESCE(a.name, item.area)
  FROM unnest(l.location) WITH ORDINALITY AS item(area, position)
  LEFT JOIN public.location_aliases AS alias
    ON alias.alias_key = lower(trim(regexp_replace(
      regexp_replace(item.area, '[^[:alnum:]]+', ' ', 'g'),
      '[[:space:]]+',
      ' ',
      'g'
    )))
  LEFT JOIN public.areas AS a ON a.id = alias.area_id
  ORDER BY item.position
);
